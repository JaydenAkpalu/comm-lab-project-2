const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const assert = require('node:assert/strict');
(async () => {
const http = require('node:http');
const fs = require('node:fs');
const path = require('node:path');
const root=path.resolve(__dirname,'..');
fs.mkdirSync(path.join(root,'documentation/screenshots'),{recursive:true});
const server=http.createServer((req,res)=>{
 const url=new URL(req.url,'http://localhost');
 const file=path.resolve(root,'.'+decodeURIComponent(url.pathname==='/'?'/index.html':url.pathname));
 if(!file.startsWith(root+path.sep)){res.writeHead(403);return res.end();}
 fs.readFile(file,(err,data)=>{
  if(err){res.writeHead(404);return res.end();}
  res.setHeader('Content-Type',({'.html':'text/html','.css':'text/css','.js':'text/javascript','.png':'image/png'})[path.extname(file)]||'application/octet-stream');
  res.end(data);
 });
});
await new Promise(resolve=>server.listen(4174,'127.0.0.1',resolve));
server.unref();
const browser = await chromium.launch({channel:'msedge',headless:true});
const page = await browser.newPage({viewport:{width:1440,height:1000}});
const errors=[]; page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://127.0.0.1:4174');
await page.locator('#introSkip').click();
await page.locator('#intro').waitFor({state:'detached'});
const count = () => page.locator('.panel:not([hidden])').count();
assert.equal(await count(),3);
await page.locator('[data-action="enter"]').scrollIntoViewIfNeeded();
await page.waitForTimeout(1200);
await page.screenshot({path:'documentation/screenshots/v02-01-invitation-desktop.png',fullPage:true});
await page.locator('[data-action="enter"]').click();
assert.equal(await count(),10);
await page.locator('[data-action="alone"]').click();
assert.equal(await page.locator('[data-response="alone"]').isVisible(),true);
assert.equal(await count(),10);
await page.waitForTimeout(1200);
await page.locator('.panel').nth(9).screenshot({path:'documentation/screenshots/v02-02-trying-alone.png'});
await page.locator('[data-action="help"]').click();
assert.equal(await count(),14);
await page.locator('[data-action="linger"]').click();
assert.equal(await page.locator('[data-response="linger"]').isVisible(),true);
await page.waitForTimeout(1200);
await page.locator('.panel').nth(13).screenshot({path:'documentation/screenshots/v02-03-before-goodbye.png'});
await page.locator('[data-action="close"]').click();
assert.equal(await count(),16);
await page.locator('#restartStory').click();
await page.locator('#introSkip').click();
await page.locator('#intro').waitFor({state:'detached'});
assert.equal(await count(),3);
await page.locator('#showAll').click();
assert.equal(await count(),16);
const mobile=await browser.newPage({viewport:{width:390,height:844},reducedMotion:'reduce'});
await mobile.goto('http://127.0.0.1:4174');
await mobile.locator('[data-action="enter"]').click();
await mobile.locator('[data-action="alone"]').click();
await mobile.locator('.panel').nth(9).screenshot({path:'documentation/screenshots/v02-04-help-mobile.png'});
assert.equal(await mobile.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
await mobile.locator('[data-action="help"]').focus();
await mobile.keyboard.press('Enter');
assert.equal(await mobile.locator('.panel:not([hidden])').count(),14);
const fallback=await browser.newPage({javaScriptEnabled:false});
await fallback.goto('http://127.0.0.1:4174');
assert.equal(await fallback.locator('.panel:not([hidden])').count(),16);
assert.equal(await fallback.locator('.story-choice:visible').count(),0);
const noCDN=await browser.newPage({reducedMotion:'reduce'});
await noCDN.route('**/cdn.jsdelivr.net/**',route=>route.abort());
await noCDN.goto('http://127.0.0.1:4174');
await noCDN.locator('[data-action="enter"]').click();
assert.equal(await noCDN.locator('.panel:not([hidden])').count(),10);
assert.deepEqual(errors,[]);
console.log('PASS: desktop progression 3/10/14/16, optional thoughts, restart, show-all, mobile layout, reduced motion, keyboard, JavaScript-disabled reading, CDN failure fallback. Screenshots saved.');
await browser.close();
server.close();
})().catch(e=>{console.error(e);process.exit(1)});
